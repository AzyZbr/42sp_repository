#include "libft.h"

int	ft_atoi(const char *np)
{
	size_t	i;
	int		sign;
	int		n;

	i = 0;
	sign = 1;
	n = 0;
	while ((np[i] >= '\t' && np[i] <= '\r')
		|| (np[i] == ' '))
		i++;
	if (np[i] == '-' || np[i] == '+')
		if (np[i++] == '-')
			sign = -1;
	while (np[i] >= '0' && np[i] <= '9')
	{
		n = (n * 10) + (np[i] - '0');
		i++;
	}
	return (sign * n);
}
